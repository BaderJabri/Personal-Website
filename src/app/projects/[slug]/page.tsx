import type { Metadata } from "next";
import Link from "next/link";
import { MDXRemote } from "next-mdx-remote/rsc";
import { PatternToy } from "@/components/client/PatternToy";
import { DemoFrame } from "@/components/demo/DemoFrame";
import { Footer } from "@/components/Footer";
import { Nav } from "@/components/Nav";
import { RibSheet } from "@/components/work/RibSheet";
import { Cover, Metrics } from "@/components/work/parts";
import { getRibSession } from "@/lib/demo";
import { getAllProjects, getProject } from "@/lib/projects";

export function generateStaticParams() {
  return getAllProjects().map((p) => ({ slug: p.slug }));
}

export const dynamicParams = false;

type Params = { params: Promise<{ slug: string }> };

export async function generateMetadata({ params }: Params): Promise<Metadata> {
  const { slug } = await params;
  const { frontmatter: fm } = getProject(slug);
  return {
    title: fm.title,
    description: fm.summary,
    alternates: { canonical: `/projects/${slug}/` },
    openGraph: { title: `${fm.title} | Bader Aljabri`, description: fm.summary, url: `/projects/${slug}/` },
  };
}

export default async function ProjectPage({ params }: Params) {
  const { slug } = await params;
  const projects = getAllProjects();
  const index = projects.findIndex((p) => p.slug === slug);
  const { frontmatter: fm, body } = projects[index];
  const next = projects[(index + 1) % projects.length];

  const links = [
    fm.links.live && { href: fm.links.live, label: "Open the app" },
    fm.links.github && { href: fm.links.github, label: "Source on GitHub" },
  ].filter((l): l is { href: string; label: string } => Boolean(l));

  return (
    <>
      <Nav current="projects" />
      <main id="main" className="wrap pt-10 md:pt-16">
        <Link href="/projects/" className="link text-sm text-pencil">
          All projects
        </Link>

        <header className="mt-10 grid gap-10 md:grid-cols-12 md:gap-x-8">
          <div className="md:col-span-7">
            <h1 className="display text-[clamp(40px,6.4vw,76px)]">{fm.transform}</h1>
            <p className="mt-6 max-w-[40ch] text-lg leading-snug md:text-xl md:leading-[1.25]">{fm.summary}</p>
          </div>
          <dl className="grid content-start gap-5 text-sm md:col-span-4 md:col-start-9 md:pt-3">
            <div>
              <dt className="text-pencil">Project</dt>
              <dd className="font-semibold">{fm.title}</dd>
            </div>
            <div>
              <dt className="text-pencil">Role</dt>
              <dd className="num">
                {fm.role}, {fm.year}
                {fm.status === "in-progress" && <span className="text-accent"> (in progress)</span>}
              </dd>
            </div>
            <div>
              <dt className="text-pencil">Built with</dt>
              <dd>{fm.stack.join(", ")}</dd>
            </div>
            {links.length > 0 && (
              <div>
                <dt className="sr-only">Links</dt>
                <dd className="flex flex-wrap gap-x-5 gap-y-1">
                  {links.map((l) => (
                    <a key={l.href} href={l.href} className="link font-semibold">
                      {l.label}
                    </a>
                  ))}
                </dd>
              </div>
            )}
          </dl>
        </header>

        <div className="mt-14 md:mt-20">
          {slug === "claude-autocad" ? (
            <>
              <DemoFrame events={getRibSession()} />
              <p className="mt-3 text-xs text-pencil">
                A scripted replay of a Claude Code session. The geometry is real NACA 2412 math, generated by the
                same code a real session would use.
              </p>
              <RibSheet events={getRibSession()} className="mt-14" />
              <p className="mt-3 text-xs text-pencil">The finished part, plotted to paper.</p>
            </>
          ) : (
            fm.cover && <Cover cover={fm.cover} sizes="(min-width: 1200px) 1136px, 100vw" eager />
          )}
          {slug === "tile-to-pattern" && (
            <section aria-labelledby="try-title" className="mt-14 rounded-[10px] border border-rule p-4 sm:p-6">
              <h2 id="try-title" className="wide text-lg font-semibold">
                Try a small version
              </h2>
              <p className="mb-6 mt-1 text-sm text-pencil">
                It runs in your browser: edit the tile, pick a layout, drag the pattern around.
              </p>
              <PatternToy />
            </section>
          )}
        </div>

        <div className="mt-14 grid gap-12 md:mt-20 md:grid-cols-12 md:gap-x-8">
          <Metrics metrics={fm.metrics} className="self-start md:col-span-3 md:!grid-cols-1" />
          <article className={`prose-sheet ${fm.metrics.length ? "md:col-span-8 md:col-start-5" : "md:col-span-8"}`}>
            <MDXRemote source={body} />
          </article>
        </div>

        {next.slug !== slug && (
          <nav aria-label="Next project" className="mt-24 border-t border-rule pt-8 md:mt-32">
            <Link href={`/projects/${next.slug}/`} className="group inline-block">
              <span className="text-sm text-pencil">Next project</span>
              <span className="display mt-2 block text-[clamp(28px,3.6vw,40px)] group-hover:text-accent">
                {next.frontmatter.transform}
              </span>
            </Link>
          </nav>
        )}
      </main>
      <Footer />
    </>
  );
}
